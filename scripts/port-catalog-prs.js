#!/usr/bin/env node
/**
 * port-catalog-prs.js
 *
 * Lands the data/repos.json additions from one or more stale community PRs
 * onto the current checkout, so a maintainer can merge them as one batch.
 *
 *   GITHUB_TOKEN=... node scripts/port-catalog-prs.js [--dry-run] [--exclude owner/repo,...] PR [PR...]
 *
 * Why this exists (#958): every new catalog entry is appended to the end of
 * repos.json, so any two open add-repo PRs conflict at the same hunk and a
 * CONFLICTING PR gets no CI at all. recover-repo-submissions.js rebases the
 * bot's own add-repo-* branches, but it cannot push to fork branches. This
 * takes the other route: lift each PR's additions and re-apply them here.
 *
 * Per PR: fetch pull/N/head, diff its repos.json against the merge-base (so
 * entries main has removed since the fork are not resurrected), then for
 * every addition:
 *   - dead on GitHub        -> skipped (it would break the stars snapshot)
 *   - renamed on GitHub     -> owner/repo/url rewritten to the current name
 *   - already in the catalog, or added by an earlier PR in the list -> skipped
 *   - otherwise appended via mergeSubmissionCandidate (normalizes category,
 *     validates the whole catalog, throws on an invalid entry)
 *
 * Only data/repos.json is written. Summaries and pages are generated by the
 * post-merge build (generate-summaries.js + build-pages.js), so the batch PR
 * stays small enough for path-filtered CI gates to run.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { githubHeaders } from "../lib/github.js";
import {
  buildRepoQuery,
  findDeadRepos,
  findRenamedRepos,
} from "../lib/catalog-health.js";
import {
  findBranchAdditions,
  mergeSubmissionCandidate,
  repoKey,
} from "../lib/repo-submission.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPOS_PATH = path.join(ROOT, "data", "repos.json");

const git = (...args) =>
  execFileSync("git", args, { cwd: ROOT, encoding: "utf-8", maxBuffer: 1024 * 1024 * 256 });

function parseArgs(argv) {
  const opts = { dryRun: false, exclude: new Set(), prs: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--dry-run") opts.dryRun = true;
    else if (arg === "--exclude") {
      for (const key of String(argv[++i] || "").split(",")) {
        if (key.trim()) opts.exclude.add(key.trim().toLowerCase());
      }
    } else if (/^#?\d+$/.test(arg)) opts.prs.push(Number(arg.replace("#", "")));
    else throw new Error(`Unknown argument: ${arg}`);
  }
  if (opts.prs.length === 0) throw new Error("Pass at least one PR number");
  return opts;
}

function prAdditions(pr) {
  const ref = `refs/port-catalog/pr${pr}`;
  git("fetch", "--quiet", "origin", `+pull/${pr}/head:${ref}`);
  const base = git("merge-base", "HEAD", ref).trim();
  const baseRepos = JSON.parse(git("show", `${base}:data/repos.json`));
  const branchRepos = JSON.parse(git("show", `${ref}:data/repos.json`));
  git("update-ref", "-d", ref);
  return findBranchAdditions(baseRepos, branchRepos);
}

async function resolveOnGitHub(entries, token) {
  const { query } = buildRepoQuery(entries);
  const res = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: { ...githubHeaders(token), "Content-Type": "application/json" },
    body: JSON.stringify({ query: `{ ${query} }` }),
  });
  if (!res.ok) throw new Error(`GitHub GraphQL failed (${res.status})`);
  const { data, errors } = await res.json();
  const unexpected = (errors || []).filter((e) => e.type !== "NOT_FOUND");
  if (unexpected.length > 0) {
    throw new Error(`GitHub GraphQL errors: ${unexpected.map((e) => e.message).join("; ")}`);
  }
  return {
    dead: new Set(findDeadRepos(entries, errors).map(repoKey)),
    renamed: new Map(findRenamedRepos(entries, data).map((r) => [r.from.toLowerCase(), r.to])),
  };
}

export async function portCatalogPrs({ prs, exclude = new Set(), dryRun = false, token }) {
  if (!token) throw new Error("GITHUB_TOKEN is required to check candidates on GitHub");

  const candidates = [];
  for (const pr of prs) {
    for (const entry of prAdditions(pr)) candidates.push({ pr, entry });
  }
  const { dead, renamed } = await resolveOnGitHub(candidates.map((c) => c.entry), token);

  let repos = JSON.parse(fs.readFileSync(REPOS_PATH, "utf-8"));
  const report = [];
  for (const { pr, entry } of candidates) {
    const original = `${entry.owner}/${entry.repo}`;
    const skip = (reason) => report.push({ pr, repo: original, result: `skipped: ${reason}` });

    if (exclude.has(original.toLowerCase())) { skip("excluded"); continue; }
    if (dead.has(original.toLowerCase())) { skip("not found on GitHub"); continue; }

    let candidate = entry;
    const current = renamed.get(original.toLowerCase());
    if (current) {
      const [owner, repo] = current.split("/");
      candidate = { ...entry, owner, repo, url: `https://github.com/${current}` };
    }
    const key = repoKey(candidate);
    if (repos.some((r) => repoKey(r) === key)) { skip("already in catalog"); continue; }

    repos = mergeSubmissionCandidate(repos, candidate);
    report.push({
      pr,
      repo: `${candidate.owner}/${candidate.repo}`,
      result: current ? `added (renamed from ${original})` : "added",
    });
  }

  if (!dryRun) fs.writeFileSync(REPOS_PATH, `${JSON.stringify(repos, null, 2)}\n`);
  return report;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  const report = await portCatalogPrs({ ...opts, token: process.env.GITHUB_TOKEN });
  for (const row of report) console.log(`#${row.pr}  ${row.repo}  ${row.result}`);
  const added = report.filter((r) => r.result.startsWith("added")).length;
  console.log(`${added} added, ${report.length - added} skipped${opts.dryRun ? " (dry run, nothing written)" : ""}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message || err);
    process.exit(1);
  });
}
